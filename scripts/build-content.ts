import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { collectArticles } from './content.ts'

const root = fileURLToPath(new URL('../', import.meta.url))
async function scan(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(dir, entry.name)
      return entry.isDirectory()
        ? scan(path)
        : Promise.resolve(
            entry.name.endsWith('.md') && entry.name !== 'README.md'
              ? [path]
              : [],
          )
    }),
  )
  return nested.flat()
}
export async function buildContent() {
  const inputs = []
  for (const [folder, demo] of [
    ['stories', false],
    ['examples', true],
  ] as const) {
    for (const path of await scan(join(root, 'content', folder)))
      inputs.push({ source: await readFile(path, 'utf8'), demo })
  }
  const articles = collectArticles(inputs)
  const output = join(root, 'src/generated/content.ts')
  await mkdir(join(dirname(output), 'articles'), { recursive: true })
  for (const article of articles)
    await writeFile(
      join(dirname(output), 'articles', `${article.id}.json`),
      JSON.stringify(article),
    )
  const catalog = articles.map(
    ({
      html: _html,
      scenes: _scenes,
      preambleHtml: _preamble,
      detailed: _detailed,
      notes: _notes,
      ...meta
    }) => meta,
  )
  await writeFile(
    join(dirname(output), 'catalog.json'),
    JSON.stringify(catalog),
  )
  const cases = articles
    .map(
      (article) =>
        `case ${JSON.stringify(article.id)}: return (await import('./articles/${article.id}.json')).default as Article`,
    )
    .join('\n')
  // Only current published IDs are referenced, including when a previous article becomes a draft.
  await writeFile(
    output,
    `// Generated by bun run content:build. Do not edit.\nimport type { Article, ArticleMeta } from '../../scripts/content'\nexport const catalog: ArticleMeta[] = ${JSON.stringify(catalog, null, 2)}\nexport async function getArticle(id: string): Promise<Article | null> {\nswitch (id) {\n${cases}\ndefault: return null\n}\n}\n`,
  )
  console.log(
    `Content: ${articles.filter((a) => !a.demo).length} published stories, ${articles.filter((a) => a.demo).length} layout examples; drafts excluded.`,
  )
}
if (import.meta.main) await buildContent()
